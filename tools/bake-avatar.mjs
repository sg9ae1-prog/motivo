// Draws the looks the page opens with, ahead of time, into assets/avatar-baked.js.
// Run after changing those looks or updating the drawing library:  node tools/bake-avatar.mjs
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
import { HERO, MINIS, FACES, renderKey, partKey } from "../assets/avatar-looks.js";

const asset = (p) => new URL(`../assets/${p}`, import.meta.url);
globalThis.window = globalThis;
vm.runInThisContext(readFileSync(asset("bigheads.js"), "utf8"));
const M = window.Motivo;

const renders = { [renderKey(HERO, 1000)]: M.render(HERO, 1000) };
for (const look of Object.values(MINIS)) renders[renderKey(look, 300)] = M.render(look, 300);
const parts = {};
for (const f of Object.values(FACES))
  for (const [kind, name] of [["eyes", f.eyes], ["brows", f.brows], ["mouth", f.mouth]]) parts[partKey(kind, name, HERO)] = M.part(kind, name, HERO);
const colors = { skin: M.colors.skin, clothing: M.colors.clothing };

writeFileSync(asset("avatar-baked.js"), `// Generated by tools/bake-avatar.mjs — do not edit by hand.\nexport const BAKED = ${JSON.stringify({ renders, parts, colors })};\n`);
// The first screen's picture of Motivo, in the page itself, with the live one's glow, ring and sheen; its inner names are suffixed so they never clash with the live drawing's.
const poster = renders[renderKey(HERO, 1000)].replace(/id="([^"]+)"/g, 'id="$1-poster"').replace(/url\(#([^)]+)\)/g, "url(#$1-poster)").replace(/href="#([^"]+)"/g, 'href="#$1-poster"');
const page = new URL("../index.html", import.meta.url);
const spot = /(<section id="meet"[\s\S]*?<div class="anchor"[^>]*>)(?:<div class="poster"[\s\S]*?<\/svg>(?:<div class="sheen"><\/div>)?<\/div>)?(<\/div>)/;
const html = readFileSync(page, "utf8");
if (!spot.test(html)) throw new Error("the first screen's spot for Motivo was not found in index.html");
writeFileSync(page, html.replace(spot, (_, open, close) => `${open}<div class="poster" aria-hidden="true"><div class="glow"></div><div class="ring"></div>${poster}<div class="sheen"></div></div>${close}`));

console.log(`baked ${Object.keys(renders).length} drawings and ${Object.keys(parts).length} face parts`);
